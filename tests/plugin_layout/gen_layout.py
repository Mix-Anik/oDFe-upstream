#!/usr/bin/env python3
"""
Writes layout_check.c: compile-time checks of the size of every struct of the API headers and the offset of every field.

The engine is compiled with gcc (or MSVC) and a plugin with q3lcc; they must agree on the layout of the structs they exchange.
The expected numbers are worked out here from the rules of C (every member of these structs is a 4 byte integer or float, or
a char array, so there is no padding to argue about), independently of both compilers. The file is compiled with each of them
and fails to compile where one differs.
"""

import re
import sys

SCALARS = {"int": 4, "unsigned": 4, "unsigned int": 4, "float": 4, "char": 1, "unsigned char": 1}


def strip(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def parse(path, structs, defines):
    text = strip(open(path).read())
    for m in re.finditer(r"^\s*#define\s+(\w+)\s+(\d+)\s*$", text, re.M):
        defines[m.group(1)] = int(m.group(2))
    for m in re.finditer(r"typedef\s+struct\s*\{(.*?)\}\s*(\w+)\s*;", text, re.S):
        fields = []
        for decl in m.group(1).split(";"):
            decl = decl.strip()
            if not decl:
                continue
            mt = re.match(r"((?:unsigned\s+)?\w+)\s+(.*)$", decl, re.S)
            ctype, rest = mt.group(1), mt.group(2)
            for d in rest.split(","):
                md = re.match(r"\s*(\w+)((?:\[\w+\])*)\s*$", d)
                dims = [defines.get(x, x) if not x.isdigit() else int(x) for x in re.findall(r"\[(\w+)\]", md.group(2))]
                fields.append((ctype, md.group(1), dims))
        structs[m.group(2)] = fields


def layout(name, structs, defines, done):
    """Returns (size, align, [(field, offset)])."""
    if name in done:
        return done[name]
    offset, align, offsets = 0, 1, []
    for ctype, field, dims in structs[name]:
        if ctype in SCALARS:
            size = a = SCALARS[ctype]
        else:
            size, a, _ = layout(ctype, structs, defines, done)
        count = 1
        for d in dims:
            count *= defines[d] if isinstance(d, str) else d
        offset = (offset + a - 1) // a * a
        offsets.append((field, offset))
        offset += size * count
        align = max(align, a)
    size = (offset + align - 1) // align * align
    done[name] = (size, align, offsets)
    return done[name]


def main():
    out = sys.argv[1]
    headers = sys.argv[2:]
    structs, defines = {}, {}
    for h in headers:
        parse(h, structs, defines)
    done = {}
    lines = ["/* Generated by gen_layout.py - do not edit. */", ""]
    for name in structs:
        size, _, offsets = layout(name, structs, defines, done)
        lines.append("ODF_SIZE( %s, %d )" % (name, size))
        for field, off in offsets:
            lines.append("ODF_OFFSET( %s, %s, %d )" % (name, field, off))
    open(out, "w").write("\n".join(lines) + "\n")
    print("%d structs" % len(structs))


main()
